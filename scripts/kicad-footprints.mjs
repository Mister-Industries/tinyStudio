#!/usr/bin/env node
/**
 * kicad-footprints.mjs: copy the footprints export/kicadMap.ts assigns into
 * src/renderer/src/circuit/export/kicadFootprints.gen.ts, so an exported HAT
 * board comes with every part already on it (export/kicadPlace.ts).
 *
 *   node scripts/kicad-footprints.mjs \
 *     --kicad "/Applications/KiCad/KiCad.app/Contents/SharedSupport/footprints" \
 *     --sparkfun <SparkFun-KiCad-Libraries checkout>/Footprints
 *
 * SparkFun- footprints come from SparkFun's KiCad libraries (CC-BY 4.0), the
 * rest from KiCad's stock libraries (CC-BY-SA 4.0 with the KiCad libraries
 * exception). See THIRD_PARTY_NOTICES.md. Re-run it when kicadMap.ts changes.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const EXPORT = resolve(__dirname, '..', 'src', 'renderer', 'src', 'circuit', 'export')

/** Every footprint id kicadMap.ts names, directly or through a constant. */
function mappedFootprints() {
  const src = readFileSync(join(EXPORT, 'kicadMap.ts'), 'utf8')
  const consts = Object.fromEntries(
    [...src.matchAll(/const (\w+) = '([^']+)'/g)].map((m) => [m[1], m[2]])
  )
  const ids = new Set([...src.matchAll(/footprint: '([^']+:[^']+)'/g)].map((m) => m[1]))
  for (const m of src.matchAll(/footprint: (\w+)\b/g)) if (consts[m[1]]) ids.add(consts[m[1]])
  return [...ids].sort()
}

function main() {
  const argv = process.argv.slice(2)
  const arg = (k) => {
    const i = argv.indexOf(k)
    return i >= 0 ? argv[i + 1] : ''
  }
  const kicad = arg('--kicad')
  const sparkfun = arg('--sparkfun')
  if (!kicad || !sparkfun) {
    console.error(
      'usage: node scripts/kicad-footprints.mjs --kicad <KiCad footprints> --sparkfun <SparkFun Footprints>'
    )
    process.exit(1)
  }
  const entries = []
  for (const id of mappedFootprints()) {
    const [lib, name] = id.split(':')
    const dir = lib.startsWith('SparkFun-') ? sparkfun : kicad
    const text = readFileSync(join(dir, `${lib}.pretty`, `${name}.kicad_mod`), 'utf8')
    entries.push([id, text.replace(/\r\n/g, '\n').trimEnd()])
  }
  const body = entries.map(([id, s]) => `  ${JSON.stringify(id)}: ${JSON.stringify(s)}`).join(',\n')
  writeFileSync(
    join(EXPORT, 'kicadFootprints.gen.ts'),
    `// Generated by scripts/kicad-footprints.mjs from SparkFun's KiCad libraries\n` +
      `// (CC-BY 4.0) and KiCad's stock footprint libraries (CC-BY-SA 4.0 with the\n` +
      `// KiCad libraries exception); see THIRD_PARTY_NOTICES.md. Do not edit:\n` +
      `// re-run the script.\n\n` +
      `/** lib:footprint → its .kicad_mod, for placing on an exported board. */\n` +
      `export const KICAD_FOOTPRINTS: Record<string, string> = {\n${body}\n}\n`
  )
  console.log(`wrote ${entries.length} footprints`)
}

main()
